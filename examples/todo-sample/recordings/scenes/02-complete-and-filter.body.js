const p = findTab('todomvc.com/examples/react');
if (!p) throw new Error('run scene 01 first: the todo tab is not open');
await prep(p);
if (await p.locator('.todo-list li').count() !== 3) throw new Error('expected the 3 todos from scene 01');
await placeCursor(p, W * 0.78, H * 0.42);
stop = await record(p, '_tmp02');
await sleep(1200);
const row = text => p.locator('.todo-list li').filter({ hasText: text });
await click(p, row('Write the shot list').locator('.toggle'));
await sleep(700);
await click(p, row('Record the scenes').locator('.toggle'));
await p.getByText('1 item left').waitFor();
await sleep(900);
await click(p, p.getByRole('link', { name: 'Active' }));
await sleep(1400);
await click(p, p.getByRole('link', { name: 'Completed' }));
await sleep(1400);
await click(p, p.getByRole('link', { name: 'All' }));
await park(p, W * 0.78, H * 0.42);
await sleep(2400);
const r = await stop(); stop = null;
return { frames: r.frames, left: await p.locator('.todo-count').innerText() };
